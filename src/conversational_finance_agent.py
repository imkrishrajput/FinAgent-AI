class ConversationalFinanceAgent:
    """
    Agent 3: answers natural-language finance questions strictly from
    Agent 2's structured analysis. Never touches raw files, never
    calculates, never gives investment/tax advice.
    """

 
    def ask(self, financial_analysis: Dict[str, Any], question: str,
             conversation_history: Optional[list] = None) -> str:
        """
        Args:
            financial_analysis: The dict produced by Agent 2
                (FinancialAnalysisAgent.analyze() or FinancialEngine.run()).
            question: The user's finance question, e.g. "Where did I spend the most?"
            conversation_history: Optional list of prior
                {"role": "user"/"assistant", "content": "..."} turns, so
                follow-up questions ("and what about last month?") keep context.
 
        Returns:
            A plain-text natural-language answer (no JSON, no markdown fences).
        """
        if not question or not question.strip():
            return "I'm unable to answer that because no question was provided."
 
        if not financial_analysis:
            return "I'm unable to answer that because the required information is not available in the financial analysis." 
        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            },
            {
                "role": "user",
                "content": self._build_user_message(
                    financial_analysis,
                    question
                )
            }
        ]

        try:
            response = chat(
                messages=messages,
                temperature=0,
                max_tokens=1024
            )

            return self._clean_response(response)

        except Exception as e:
            return f"Error while generating response: {str(e)}"
 
    def _build_user_message(
        self,
        financial_analysis: Dict[str, Any],
        question: str
    ) -> str:

        import json

        analysis = {
            "financial_summary": financial_analysis.get("financial_summary"),
            "category_analysis": financial_analysis.get("category_analysis"),
            "merchant_analysis": financial_analysis.get("merchant_analysis"),
            "payment_analysis": financial_analysis.get("payment_analysis"),
            "spending_patterns": financial_analysis.get("spending_patterns"),
            "top_5_expenses": financial_analysis.get("top_5_expenses"),
            "top_5_income": financial_analysis.get("top_5_income"),
            "budget_recommendations": financial_analysis.get("budget_recommendations"),
            "financial_report": financial_analysis.get("financial_report"),
        }

        return (
            "Financial Analysis:\n"
            + json.dumps(
                financial_analysis,
                indent=2,
                ensure_ascii=False
            )
            + "\n\nUser Question:\n"
            + question
        )
 
    @staticmethod
    def _clean_response(raw_text: str) -> str:
        """Strip any stray markdown fences the model might add, just in case."""
        cleaned = raw_text.strip()
        cleaned = re.sub(r"^```[a-zA-Z]*", "", cleaned).strip()
        cleaned = re.sub(r"```$", "", cleaned).strip()
        return cleaned
 
 
